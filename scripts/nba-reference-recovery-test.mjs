import assert from 'node:assert/strict';
import { nbaPreseasonReference } from '../lib/nba/analysis-reference.js';
import { nbaLatestBoardDate, nbaCompletionSummary } from '../lib/nba/analysis-ui-policy.js';
import { defaultTraining } from '../lib/nba/analysis-training.js';
const game = { league: 'NBA', seasonType: 'preseason', season: { year: 2027 }, taipeiDate: '2026-10-06', home: { id: 'nba:espn:team:1' }, away: { id: 'nba:espn:team:2' } };
const result = nbaPreseasonReference(game, defaultTraining.history);
assert.ok(result); assert.equal(result.calibrated, false);
for (const key of ['direction', 'probabilityEstimate', 'expectedNet']) assert.equal(result[key], null);
assert.equal(result.total, result.homePoints + result.awayPoints);
assert.equal(nbaPreseasonReference({ ...game, seasonType: 'regular' }, defaultTraining.history), null);
assert.equal(nbaPreseasonReference(game, []), null);
assert.equal(nbaPreseasonReference(game, [...defaultTraining.history, defaultTraining.history[0]]), null);
assert.deepEqual(nbaPreseasonReference(game, [...defaultTraining.history, { year: 2027, seasonType: 'preseason', date: '2026-10-07', homeScore: 999 }]), result);
const now = Date.parse('2026-10-05T18:00:00Z');
const board = { status: 'fresh', boardDate: '2026-10-06', observedAt: new Date(now).toISOString() };
assert.equal(nbaLatestBoardDate(board, '2026-10-05', now), '2026-10-06');
assert.equal(nbaLatestBoardDate(board, '2026-10-05', now + 180001), '2026-10-05');
assert.equal(nbaLatestBoardDate({ ...board, boardDate: '2026-10-08' }, '2026-10-05', now), '2026-10-05');
assert.equal(nbaLatestBoardDate(board, '2026-10-07', now), '2026-10-07');
assert.equal(nbaLatestBoardDate(board, 'invalid', now), 'invalid');
assert.equal(nbaCompletionSummary({ total: 3, results: [{ ok: true, payload: { status: 'reference' } }, { ok: false, payload: { status: 'insufficient' } }, { ok: false }] }), 'NBA 已處理 3/3 場｜校正分析 0｜跨季基準 1｜資料不足 1｜核對阻擋 0｜失敗 1');
console.log('NBA preseason reference: separate uncalibrated estimate, sample guards, no future leakage, latest-date freshness and exact completion counts PASS');
