import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { gunzipSync } from 'node:zlib';
import { signReferenceReceipt, verifyReferenceReceipt } from '../lib/market-integrity-v1.js';
import { referenceAttempt, referenceFailureCode, referenceGameMap } from '../lib/reference-acquisition-evidence.js';
import { readReplayArtifact, replayEnvironmentEvidence, replayEnvironmentSummary } from '../lib/replay-environment-evidence.js';
import { modelValidationLink } from '../lib/model-validation-registry.js';
import { replayEvidenceView } from '../lib/analysis-evidence-export-v2.js';

const env = { MARKET_INTEGRITY_SECRET: 'unit-only-receipt-signing-key' };
const game = { league: 'MLB', gamePk: 823250, gameDate: '2099-09-09T01:40:00.000Z', taipeiDate: '2099-09-09', gameNumber: 1, awayTeamId: 120, homeTeamId: 135 };
assert.equal(referenceFailureCode({ name: 'AbortError' }), 'TIMEOUT');
assert.equal(referenceFailureCode({ httpStatus: 401, message: 'Usage quota has been reached' }), 'QUOTA_EXHAUSTED');
assert.equal(referenceFailureCode({ httpStatus: 401 }), 'AUTH_REJECTED');
assert.equal(referenceFailureCode({ httpStatus: 429 }), 'RATE_LIMITED');
assert.equal(referenceFailureCode({ httpStatus: 404 }), 'HTTP_404');
assert.equal(referenceFailureCode({ code: 'INVALID_JSON' }), 'INVALID_JSON');
assert.equal(referenceFailureCode({ message: 'unknown' }), 'REQUEST_FAILED');
const evidence = { scope: 'ACQUISITION_ONLY_NOT_PRICE_VALIDATION', capturedAt: '2099-09-08T20:00:00Z', cacheStatus: 'MISS',
  attempts: [referenceAttempt('TEST_PROVIDER', 'PRICES', { status: 'FAILED', reasonCode: 'QUOTA_EXHAUSTED', httpStatus: 401 })] };
const receipt = await signReferenceReceipt('MLB', game, evidence, env);
assert.equal((await verifyReferenceReceipt(receipt, 'MLB', game, env)).status, 'SIGNATURE_VERIFIED');
const tampered = structuredClone(receipt);
tampered.payload.evidence.attempts[0].reasonCode = 'SUCCESS';
assert.equal((await verifyReferenceReceipt(tampered, 'MLB', game, env)).status, 'REJECTED');
assert.equal((await verifyReferenceReceipt(receipt, 'MLB', { ...game, gamePk: 823500 }, env)).status, 'REJECTED');
assert.equal((await verifyReferenceReceipt(receipt, 'NPB', { ...game, league: 'NPB' }, env)).status, 'REJECTED');
assert.equal((await verifyReferenceReceipt(null, 'MLB', game, env)).status, 'UNKNOWN');
assert.equal(referenceGameMap({ games: [], receipts: [{ gamePk: game.gamePk, receipt }] }).get(game.gamePk).referenceEvidence, receipt);
assert.equal(JSON.stringify(receipt).includes(env.MARKET_INTEGRITY_SECRET), false);
const cached = await signReferenceReceipt('MLB', game, { ...evidence, cacheStatus: 'HIT', servedAt: '2099-09-08T20:00:10Z' }, env);
const checked = await verifyReferenceReceipt(cached, 'MLB', game, env);
assert.equal(checked.capturedAt, evidence.capturedAt, 'Cache service must not invent a fresh acquisition time');
assert.equal(checked.cacheStatus, 'HIT');

const artifact = readReplayArtifact();
assert.ok(artifact?.content, 'Build must generate a source artifact');
const raw = gunzipSync(Buffer.from(artifact.content, 'base64'));
assert.equal(createHash('sha256').update(raw).digest('hex'), artifact.sourceSha256);
const archive = JSON.parse(raw);
for (const [file, contents] of Object.entries(archive.files)) assert.equal(contents, fs.readFileSync(file, 'utf8'), `Exact source archived: ${file}`);
assert.equal(createHash('sha256').update(archive.files['package-lock.json']).digest('hex'), artifact.lockSha256);
const analysis = { calculationSettings: { rebate: 0.015, nested: { value: 0.1234567890123456 } } };
const runtime = replayEnvironmentEvidence(analysis, 'MLB', { modelVersion: 'test-model' });
assert.deepEqual(runtime.config.calculationSettings, analysis.calculationSettings);
analysis.calculationSettings.nested.value = 0;
assert.notEqual(runtime.config.calculationSettings.nested.value, 0, 'Settings are captured, not a mutable alias');
assert.equal(runtime.executionStatus, 'NOT_EXECUTED_FROM_ARCHIVE');
assert.equal(runtime.modelValidation.status, 'NOT_REGISTERED');
assert.equal(replayEnvironmentSummary(null).status, 'HISTORICAL_EVIDENCE_NOT_RECORDED');
assert.equal(replayEnvironmentSummary(runtime).sourceArtifact.content, undefined);
assert.equal(replayEvidenceView(runtime).sourceArtifact.content, undefined);
assert.equal(modelValidationLink('MLB', 'test-model').scope, 'MODEL_VERSION_COHORT_NOT_SINGLE_GAME');
assert.notEqual(modelValidationLink('MLB', 'test-model').url, modelValidationLink('NPB', 'test-model').url);
console.log('PASS evidence completion: signed failures, game/league isolation, cache timestamps, exact source/lock archive, settings and historical boundaries');
