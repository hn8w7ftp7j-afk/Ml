import fs from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { fitSoccerConditionsResearch,soccerConditionsHash,SOCCER_CONDITIONS_MODEL_VERSION } from '../lib/soccer/conditions-model.js';

const leagues={};
for(const league of ['epl','ucl']){
  const input=JSON.parse(gunzipSync(fs.readFileSync(`research/soccer/${league}-history.json.gz`)));
  leagues[league]=fitSoccerConditionsResearch(input.rows,league);
  console.log(JSON.stringify({league,training:leagues[league].validation.train.games,validation:leagues[league].validation.validation.games,
    test:leagues[league].validation.test.games,selectedPenalty:leagues[league].selectedPenalty,
    baselineTest:leagues[league].validation.baselineTest.scoreLogLoss,challengerTest:leagues[league].validation.test.scoreLogLoss,
    delta:leagues[league].validation.deltaScoreLogLoss,formalEligible:false}));
}
const body={version:SOCCER_CONDITIONS_MODEL_VERSION,createdAt:new Date().toISOString(),leagues,formalEligible:false,accepted:false};
const artifact={...body,contentHash:soccerConditionsHash(body)};
fs.writeFileSync('research/soccer/conditions-research.json',JSON.stringify(artifact,null,2)+'\n');
fs.writeFileSync('lib/soccer/conditions-frozen.js','// Generated by scripts/soccer-conditions-build.mjs. Retrospective research only.\nconst artifact='+JSON.stringify(artifact)+';\nexport function soccerConditionsArtifacts(){return structuredClone(artifact);}\n');
