import assert from 'node:assert/strict';
import { starterInningsDisplay, runExplanationDisplay, externalVerificationExplanation, sourceStatusLabel, bullpenEvidenceDisplay, lineupCoverageDisplay } from '../lib/mlb-diagnostic-display-v1.js';
import { expectedStarterInningsV13 } from '../lib/mlb-context-v13.js';
import { estimateRunProfileV13 } from '../lib/joint-score-v13.js';

const historical = { inningsPitched: 166 + 1 / 3, gamesStarted: 29, gamesPitched: 29, starterOnly: true };
const projected = expectedStarterInningsV13(historical, { probableId: 123 });
assert.equal(projected.expectedInningsStatus, 'CONFIRMED', 'legacy quality input must remain unchanged');
assert.equal(starterInningsDisplay(projected).estimateStatus, 'PROJECTED');
assert.equal(projected.expectedInningsCalculation.branch, 'HISTORICAL_IP_PER_START');
assert.equal(projected.expectedInnings, historical.inningsPitched / 29);
const legacy = structuredClone(projected); delete legacy.expectedInningsCalculation;
assert.equal(starterInningsDisplay(legacy).calculation, null, 'never invent historical branch evidence');
assert.equal(starterInningsDisplay({}), null);
const context = { away: { starter: projected }, home: { starter: projected } };
const oldContext = { away: { starter: legacy }, home: { starter: legacy } };
assert.deepEqual(estimateRunProfileV13(context), estimateRunProfileV13(oldContext), 'trace must not change run profile or uncertainty');
const report = { calculation: { diagnostics: { awayBullpen: { factor: .96, proxy: 'RELIEF_ONLY_PIT', season: { innings: 1288 }, recent: { innings: 119 } } } } };
const original = JSON.stringify(report);
const display = runExplanationDisplay(report);
assert.equal(JSON.stringify(report), original, 'saved report must be immutable');
assert.equal(display.calculation.diagnostics.awayBullpen.factor, .96);
assert.equal(display.calculation.diagnostics.awayBullpen.season, undefined);
assert.equal(display.calculation.diagnostics.teamPitchingReference.away.season.innings, 1288);
assert.match(externalVerificationExplanation({ priorIneligibleReason: '缺少5分鐘內獨立國際市場同合約價格' }), /未保存/);
assert.match(externalVerificationExplanation(null), /未保存/);
assert.match(externalVerificationExplanation({ referencePriorEligible: true }, false), /有效期限/);
assert.equal(externalVerificationExplanation({}, true), '');
assert.equal(sourceStatusLabel('starterExpectedInnings', 'CONFIRMED'), '局數歷史輸入：CONFIRMED／預估局數：PROJECTED');
assert.equal(sourceStatusLabel('weather', 'PROJECTED'), null);
const bullpenRow = { asOf: '2026-09-08', sources: [{ purpose: 'CURRENT_ROSTER_MEMBERSHIP', asOf: '2026-09-08' }], players: [{ name: 'Gil', metrics: { inningsPitched: 2 }, metricAsOf: '2026-09-07' }, { name: 'Warren', metrics: { inningsPitched: 3 } }], coverage: { usage: { games: [{ fetched: true, date: '2026-09-06' }, { fetched: false, date: '2026-09-07' }] } } };
const before = JSON.stringify(bullpenRow);
assert.deepEqual(bullpenEvidenceDisplay(bullpenRow), { rosterDates: '2026-09-08', metricDates: '2026-09-07', metricDatesIncomplete: true, latestUsageDate: '2026-09-06', samples: [{ name: 'Gil', innings: 2 }, { name: 'Warren', innings: 3 }] });
assert.equal(JSON.stringify(bullpenRow), before);
assert.equal(bullpenEvidenceDisplay({ asOf: '2026-09-08' }).rosterDates, '未保存', 'must not infer roster date from aggregate asOf');
assert.equal(bullpenEvidenceDisplay().latestUsageDate, '未保存');
const missingRates = { coverage: { identityCount: 9, expectedCount: 9, metricCoverage: 1, modelMetricCoverage: 1 }, reportedBattingRates: Array.from({ length: 9 }, () => ({ statistics: null })) };
const originalRates = JSON.stringify(missingRates);
assert.match(lineupCoverageDisplay(missingRates), /系統回報模型用指標覆蓋 9\/9.*未提供逐人打擊率/);
assert.match(lineupCoverageDisplay({ coverage: { metricCoverage: 1 } }), /模型用指標覆蓋 未提供/, 'do not substitute observed coverage for model coverage');
assert.match(lineupCoverageDisplay({ coverage: { expectedCount: 8, modelMetricCoverage: .5 }, reportedBattingRates: [{ statistics: { average: 0 } }] }), /覆蓋 4\/8.*已列 1\/8/, 'zero rates remain present and denominator comes from evidence');
