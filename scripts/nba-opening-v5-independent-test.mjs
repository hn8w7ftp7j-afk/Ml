import assert from 'node:assert/strict';
import fs from 'node:fs';
import {openingIndependentHistory} from '../lib/nba/opening-independent-history.js';
import {evaluateTotalsV5Independent,TOTALS_V5_FROZEN_SELECTION_HASH} from '../lib/nba/opening-v5-independent-validation.js';
import {totalsV5Hash} from '../lib/nba/opening-research-v5.js';
import {assertTotalsV3Replay} from '../lib/nba/opening-research-v3.js';
const read=path=>JSON.parse(fs.readFileSync(path,'utf8'));
const selection=read('docs/nba-opening-v5-selection.json'),developmentEvidence=read('docs/nba-opening-v5-development.json');
const recorded=read('docs/nba-opening-v5-independent.json');
assert.equal(totalsV5Hash(selection),TOTALS_V5_FROZEN_SELECTION_HASH);
assert.equal(totalsV5Hash(recorded),'3ecc98ddb6e3f4038056ea96d2727c486a6b6c30dc355e1b4f8fa3f738cbb328');
assert.equal(recorded.status,'BLOCKED_HOLDOUT_FAILED');
assert.equal(recorded.holdoutConsumed,true);assert.equal(recorded.reselectionAllowed,false);
assert.equal(recorded.targets.fullTotal.passed,false);
assert.deepEqual(recorded.targets.fullTotal.reasons,['earlyModelMAE_worse_than_baseline']);
assert.equal(recorded.targets.halfTotal.passed,true);
const options={archiveEvidence:openingIndependentHistory,developmentEvidence,selectionFrozenCommit:recorded.selectionFrozenCommit};
assert.throws(()=>evaluateTotalsV5Independent(openingIndependentHistory.history,{...selection,independentHoldoutYear:2016},options),/FROZEN_SELECTION/);
assert.throws(()=>evaluateTotalsV5Independent(openingIndependentHistory.history,selection,{...options,selectionFrozenCommit:null}),/FREEZE_COMMIT/);
assert.throws(()=>evaluateTotalsV5Independent(openingIndependentHistory.history,selection,{...options,archiveEvidence:{}}),/SOURCE_UNVERIFIED/);
assertTotalsV3Replay(evaluateTotalsV5Independent(openingIndependentHistory.history,selection,options),recorded);
console.log('PASS frozen V5 consumed2017 replay: full earlyMAE failure retained, half pass retained, source/selection/commit rejection, no reselection');
