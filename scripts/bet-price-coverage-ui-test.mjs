import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { transform } from 'next/dist/build/swc/index.js';
import { summarizeOriginalBetPrices as sync, summarizeOriginalBetPricesAsync as asyncSummary } from '../lib/bet-price-summary.js';
import { moneyText } from '../lib/money-display.js';
const bets=Array.from({length:180},(_,i)=>({id:`nba:${i}`,league:'NBA',status:'SETTLED'}));
const before=JSON.stringify(bets),s=sync(bets);
assert.equal(s.unsupported,180);assert.equal(s.comparable,0);assert.equal(s.eligible,180);
assert.deepEqual(await asyncSummary(bets,{}, {yieldControl:async()=>{},compare:()=>{throw Error('NBA must not enter baseball comparison');}}),s);
assert.equal(JSON.stringify(bets),before);
const source=fs.readFileSync('app/page.js','utf8');
const jsx=source.slice(source.indexOf('function SummaryCards('),source.indexOf('function BreakdownButton('));
const {code}=await transform(jsx+'\nglobalThis.Card=SummaryCards;', {filename:'summary.jsx',jsc:{parser:{syntax:'ecmascript',jsx:true},transform:{react:{runtime:'classic'}}},module:{type:'commonjs'}});
const ctx={React,moneyText,pct:()=> '—'};vm.createContext(ctx);vm.runInContext(code,ctx);
const render=x=>renderToStaticMarkup(React.createElement(ctx.Card,{summary:{bets:180,netPnl:400000},originalPriceSummary:x}));
const html=render(s);assert.match(html,/NBA 尚未接入比較（180 筆）/);assert.doesNotMatch(html,/總數 0|優 0|劣 0/);assert.match(html,/400,000元/);
assert.match(render(sync([{id:'mlb',league:'MLB'}])),/尚無可比較盤口（1 筆缺資料）/);
assert.match(render(null),/計算中/);assert.match(render({unavailable:true}),/暫時無法計算/);
assert.match(render(sync([])),/無有效下注紀錄/);
console.log('PASS shipped coverage UI: 180 NBA unsupported, missing evidence, empty/error/loading states, immutable ledger and isolated payoff math');
