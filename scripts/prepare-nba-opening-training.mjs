import fs from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { buildOpeningTraining, OPENING_VARIABLES, openingVariableAccepted } from '../lib/nba/opening-core.js';
import { openingValidation } from '../lib/nba/opening-validation.js';
const archive=JSON.parse(await fs.readFile(process.argv[2],'utf8'));
if(archive.kind!=='NBA_OPENING_VERIFIED_REGULAR_ARCHIVE'||archive.missing?.length||archive.sources.length<500)throw Error('Opening history incomplete');
const candidates=[];
for(const priorWeight of [10,20,40]){
  const t=buildOpeningTraining(archive.history,{priorWeight,ridgePenalty:1000});
  const dev=openingValidation(t,2025);
  candidates.push({priorWeight,t,development:dev,loss:OPENING_VARIABLES.reduce((s,k)=>s+dev.metrics[k].modelMAE/dev.metrics[k].baselineMAE,0)});
}
const selected=candidates.sort((a,b)=>a.loss-b.loss||a.priorWeight-b.priorWeight)[0];
// Freeze selection using 2025 development only; evaluate 2026 ONCE afterwards.
const holdout=openingValidation(selected.t,2026);
const acceptance=Object.fromEntries(OPENING_VARIABLES.map(k=>{
  const m=holdout.metrics[k];
  return[k,{accepted:openingVariableAccepted(m),
    basis:'2026_holdout_full_and_early_MAE_and_reference_threshold_Brier_LogLoss_not_worse_than_prior_team_baseline'}];
}));
const data={kind:'NBA_OPENING_FIXED_TRAINING',...selected.t,history:archive.history,acceptance,
  validation:{developmentYear:2025,holdoutYear:2026,selection:'minimum_sum_of_four_relative_MAEs_on_2025_only',
    candidates:candidates.map(c=>({priorWeight:c.priorWeight,developmentLoss:c.loss})),development:selected.development,holdout},
  provenance:{sourceRole:archive.sourceRole,sources:archive.sources,archiveHash:createHash('sha256').update(JSON.stringify(archive)).digest('hex'),retrievedAt:archive.retrievedAt,
    quarterBasis:'first_two_verified_periods_not_full_total_divided_by_two',ridgePenalty:1000,priorWeight:selected.priorWeight,minimumResiduals:50,
    strictPointInTime:false,promotionEligible:false}};
const compressed=gzipSync(Buffer.from(JSON.stringify(data))).toString('base64');
await fs.writeFile('lib/nba/opening-training.js',`// Generated by scripts/prepare-nba-opening-training.mjs. Retrospective source archive; no betting validation claim.\nimport{gunzipSync}from'node:zlib';\nif(typeof window!=='undefined')throw Error('NBA_OPENING_TRAINING_SERVER_ONLY');\nconst freeze=x=>{if(x&&typeof x==='object'){Object.values(x).forEach(freeze);Object.freeze(x);}return x;};\nexport const openingTraining=freeze(JSON.parse(gunzipSync(Buffer.from('${compressed}','base64')).toString()));\n`);
const report={modelVersion:data.modelVersion,games:data.history.length,features:data.features.length,residuals:data.observations.length,sources:data.provenance.sources.length,archiveHash:data.provenance.archiveHash,priorWeight:data.priorWeight,ridgePenalty:data.ridgePenalty,acceptance,validation:data.validation};
await fs.writeFile('docs/nba-opening-validation.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({...report,validation:{...report.validation,development:undefined}}));
