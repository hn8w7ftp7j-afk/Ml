import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeSoccerWyscoutShotDataset, SOCCER_WYSCOUT_SOURCE_CONTRACT, soccerWyscoutShotHash } from '../lib/soccer/wyscout-shot-source.js';
import { fitSoccerShotXgResearch, soccerShotXgAggregateReport, soccerShotXgHash,
  SOCCER_SHOT_XG_RESEARCH_VERSION } from '../lib/soccer/shot-xg-research.js';

// Deliberate offline research build, never a request-time fit or an automatic
// network download. Inputs must match the reviewed original open-data pins.
const args = process.argv.slice(2), project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const option = name => { const index = args.indexOf(name); return index >= 0 ? args[index + 1] : null; };
const cacheOption = option('--cache');
if (!cacheOption) throw Error('SHOT_XG_BUILD_REQUIRES_REVIEWED_PRIVATE_CACHE');
if (args.some((value, index) => index % 2 === 0 && !['--cache', '--private-output'].includes(value)) || args.length % 2)
  throw Error('SHOT_XG_BUILD_OPTIONS_INVALID');
const cache = path.resolve(cacheOption), privateOutput = path.resolve(option('--private-output') || path.join(cache, 'shot-xg-private-fit.json'));
if (privateOutput === project || privateOutput.startsWith(`${project}${path.sep}`))
  throw Error('SHOT_XG_PRIVATE_MODEL_MUST_STAY_OUTSIDE_REPOSITORY');
const files = { events: 'events_England.native-shots.json', matches: 'matches_England.json',
  eventMapping: 'eventid2name.csv', tagMapping: 'tags2name.csv' };
const document = kind => {
  const file = path.join(cache, files[kind]), text = fs.readFileSync(file, 'utf8');
  const { hash: _hash, ...contract } = SOCCER_WYSCOUT_SOURCE_CONTRACT.documents[kind];
  return { text, source: { provider: 'WYSCOUT_OPEN_DATA', ...contract,
    contentHash: soccerWyscoutShotHash(text), fetchedAt: fs.statSync(file).mtime.toISOString() } };
};
const dataset = normalizeSoccerWyscoutShotDataset({ eventsDocument: document('events'), matchesDocument: document('matches'),
  eventsMappingDocument: document('eventMapping'), tagsMappingDocument: document('tagMapping') });
if (!dataset.ok || dataset.synthetic || dataset.sourceAuthenticationVerified !== true)
  throw Error(`SHOT_XG_AUTHENTIC_SOURCE_REQUIRED_${dataset.reason || 'SOURCE_UNVERIFIED'}`);
const privateReport = fitSoccerShotXgResearch(dataset), aggregate = soccerShotXgAggregateReport(privateReport);
const createdAt = new Date().toISOString();
const artifact = { version: SOCCER_SHOT_XG_RESEARCH_VERSION, type: 'AGGREGATE_SHOT_XG_RESEARCH_ARTIFACT',
  createdAt, provider: 'WYSCOUT_OPEN_DATA', reports: { epl: aggregate }, synthetic: false,
  accepted: false, formalEligible: false, calibrationEligible: false, promotionEligible: false,
  modelEffectApplied: false, executable: false, historicalAvailabilityVerified: false,
  independentUntouchedTestVerified: false, currentSeasonCoverageVerified: false, uclCoverageVerified: false,
  W: null, R: null, S: null };
artifact.contentHash = soccerShotXgHash(artifact);
fs.mkdirSync(path.dirname(privateOutput), { recursive: true });
fs.writeFileSync(privateOutput, JSON.stringify(privateReport), { mode: 0o600 });
const research = path.join(project, 'research/soccer/shot-xg'); fs.mkdirSync(research, { recursive: true });
fs.writeFileSync(path.join(research, 'research-report.json'), `${JSON.stringify(artifact, null, 2)}\n`);
fs.writeFileSync(path.join(project, 'lib/soccer/shot-xg-frozen.js'),
  `// Generated by soccer-shot-xg-build.mjs. Retrospective aggregate only; no production model.\nconst data=${JSON.stringify(artifact)};\nexport function soccerShotXgResearchArtifacts(){return structuredClone(data);}\n`);
console.log(JSON.stringify({ createdAt, artifactHash: artifact.contentHash, sourceCollection: aggregate.sourceCollection,
  coverage: aggregate.coverage, calibrationStatus: aggregate.calibrationStatus,
  holdout: Object.fromEntries(Object.entries(aggregate.evaluation.test).map(([name, value]) => [name,
    value ? { games: value.games, shots: value.shots, brier: value.brier, logLoss: value.logLoss,
      predictedMean: value.predictedMean, observedGoalRate: value.observedGoalRate, calibrationError: value.calibrationError } : null])),
  interpretation: aggregate.interpretation, formalEligible: false }, null, 2));
