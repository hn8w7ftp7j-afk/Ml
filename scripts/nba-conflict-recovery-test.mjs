import assert from 'node:assert/strict';
import {recoverNbaConflict,NBA_CONFLICT_RECOVERY_KEY as KEY} from '../reader/nba-conflict-recovery.js';
import {nbaMarketDisplayState} from '../lib/nba/market-display-state.js';
import {sanitizeDiagnosticReport} from '../reader/diagnostic-schema.js';
let state={},calls=[];
const storage={get:async()=>structuredClone(state),set:async value=>Object.assign(state,structuredClone(value))};
const tabs=[1,2].map(id=>({id,url:'https://www.tai888.in/newapp/#/BS'}));
const selection={error:'conflicting-duplicate-tabs',boardDate:'2026-11-07',conflictingTabIds:[1,2,999],assessed:[1,2,999].map(tabId=>({ok:true,candidate:{tabId,parsed:{league:'NBA'}}}))};
const original=structuredClone(selection);
const options={tabs,storage,reload:async id=>calls.push(id),now:100000};
const first=await recoverNbaConflict(selection,options);
assert.equal(first.state,'REQUESTED');assert.equal(first.attemptCount,1);
assert.equal(first.attemptedTabCount,2);assert.equal(first.refreshedTabCount,2);
assert.deepEqual(calls,[1,2]);assert.deepEqual(selection,original,'recovery cannot grant authority or replace prices');
assert.equal((await recoverNbaConflict(selection,{...options,now:110000})).state,'ALREADY_ATTEMPTED');
assert.deepEqual(calls,[1,2],'cooldown prevents immediate refresh storms');
assert.equal((await recoverNbaConflict(selection,{...options,now:110000,manual:true})).state,'ALREADY_ATTEMPTED');
assert.equal((await recoverNbaConflict(selection,{...options,now:190000})).attemptCount,2,'second automatic attempt is allowed after failed first refresh');
assert.equal((await recoverNbaConflict(selection,{...options,now:280000})).attemptCount,3);
assert.equal((await recoverNbaConflict(selection,{...options,now:900000})).state,'EXHAUSTED','persistent budget survives worker restart and long elapsed time');
assert.equal(calls.length,6,'automatic recovery is bounded to three refreshes per source');
assert.equal((await recoverNbaConflict(selection,{...options,now:900000,manual:true})).attemptCount,4,'explicit manual retry remains possible after cooldown');
assert.equal((await recoverNbaConflict(selection,{...options,now:990000})).state,'EXHAUSTED');
for(const error of ['conflicting-duplicate-frames','conflicting-duplicate-rows','no-complete-tab'])
 assert.equal(await recoverNbaConflict({...selection,error},{...options,manual:true,now:1200000}),null);
assert.equal((await recoverNbaConflict({...selection,boardDate:'2026-11-08'},{...options,now:1200000})).attemptCount,1,'a new board date starts a separate bounded incident');
state={};calls=[];
assert.equal(await recoverNbaConflict(selection,{...options,tabs:[tabs[0],{id:2,url:'https://tai888.in.attacker.test/'}]}),null);
assert.deepEqual(calls,[]);
const partial=await recoverNbaConflict(selection,{...options,reload:async id=>{if(id===1)throw Error('tab closed');calls.push(id);}});
assert.equal(partial.state,'REQUESTED');assert.equal(partial.refreshedTabCount,1);
assert.ok(state[KEY]);
state={[KEY]:{at:100000}};
assert.equal((await recoverNbaConflict(selection,{...options,now:110000})).state,'ALREADY_ATTEMPTED','legacy installed recovery state retains cooldown');
assert.equal((await recoverNbaConflict(selection,{...options,now:190000})).attemptCount,2,'legacy single-attempt state gains only the remaining budget');
state={};
const failed=await recoverNbaConflict(selection,{...options,reload:async()=>{throw Error('reload unavailable');}});
assert.equal(failed.state,'FAILED');assert.equal(failed.refreshedTabCount,0);
assert.equal(state[KEY].attemptCount,1,'failed browser reloads still consume their durable retry budget');
const clean=sanitizeDiagnosticReport({schema:'READER-DIAGNOSTICS-v1',reportId:'11111111-1111-4111-8111-111111111111',readerVersion:'2.1.56',createdAt:new Date().toISOString(),leagues:{NBA:{state:'error',conflictRecovery:first},EPL:{state:'error',conflictRecovery:first}}});
assert.deepEqual(clean.leagues.NBA.conflictRecovery,first,'installed Reader and API preserve typed recovery evidence');
assert.equal(clean.leagues.EPL.conflictRecovery,undefined,'NBA recovery cannot become soccer recovery');
assert.deepEqual(sanitizeDiagnosticReport(clean),clean,'double sanitization is stable');
const quote={line:'220.5',overWater:.94,underWater:.94},row={quote:{fullTotal:quote},jobState:'ready',result:{marketAnalyses:{fullTotal:{status:'unavailable',reason:'此盤口尚未開盤'}}}};
assert.equal(nbaMarketDisplayState(row,'fullTotal').label,'待補分析','new quote must not inherit game completed badge or old unopened reason');
assert.equal(nbaMarketDisplayState(row,'firstHalfTotal').label,'盤口待同步');
assert.match(nbaMarketDisplayState(row,'firstHalfTotal').message,/不代表莊家尚未開盤/);
row.result.marketAnalyses.fullTotal={status:'ready',quote:{...quote}};
assert.equal(nbaMarketDisplayState(row,'fullTotal').label,'已分析');
row.quote.fullTotal={...quote,line:'221平'};
assert.equal(nbaMarketDisplayState(row,'fullTotal').label,'待重新分析');
row.result.marketAnalyses.fullTotal={status:'insufficient',reason:'OOS 未通過'};
assert.equal(nbaMarketDisplayState(row,'fullTotal').label,'待驗證');
assert.equal(row.quote.firstHalfTotal,undefined,'display never synthesizes half markets');
console.log('PASS NBA recovery: bounded reload, persistence, URL scope, no price selection; market-level stale/missing/validation display');
